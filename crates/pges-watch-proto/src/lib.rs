//! The pges sequencer's gRPC watch service, `pges.watch.v1`: the protobuf messages, and the tonic client and
//! server generated from `proto/pges/watch/v1/watch.proto`.
//!
//! The leading sequencer streams each store's high-water mark (the store's newest position, each category's
//! newest position, and the WAL position replica readers wait for) to subscribers, which read the log when a
//! watched position has moved. `pges-sequencer` serves it (feature `watch-grpc`), and `pges-subscribe`'s
//! `GrpcWaker` consumes it (feature `wake-grpc`). Clients in other languages generate their own code from the
//! proto file, which this crate ships.
//!
//! The generated code is checked in, so building this crate needs neither `protoc` nor a build script; a test
//! generates it again and fails if it differs.
//!
//! # Features
//!
#![cfg_attr(
    feature = "client",
    doc = " - `client`: [`v1::watch_client::WatchClient`]."
)]
#![cfg_attr(
    not(feature = "client"),
    doc = " - `client`: `v1::watch_client::WatchClient`."
)]
#![cfg_attr(
    feature = "server",
    doc = " - `server`: [`v1::watch_server::Watch`], the trait a server implements, and [`v1::watch_server::WatchServer`]."
)]
#![cfg_attr(
    not(feature = "server"),
    doc = " - `server`: `v1::watch_server::Watch`, the trait a server implements, and `v1::watch_server::WatchServer`."
)]
//!
//! Without either, the crate holds the messages only.
//!
//! # Compatibility
//!
//! The package is versioned: a shape change is a new package (`pges.watch.v2`), never an edit of `v1`. Fields
//! and enum values may be added to `v1` under new numbers; existing numbers are never reused. Readers ignore
//! fields they do not know; for an enum value they do not know, a getter such as
//! [`v1::StatusResponse::state`] returns the `UNSPECIFIED` value and the field keeps the number.
#![cfg_attr(docsrs, feature(doc_cfg))]

pub mod v1 {
    //! `pges.watch.v1`, generated by prost and tonic.

    use pges_core::{category, high_water, lsn, position};

    include!("generated/pges.watch.v1.rs");

    impl WatchResponse {
        /// The message for `high_water`, announced by the term with this `fence`.
        pub fn new(fence: u64, high_water: &high_water::HighWater) -> Self {
            Self {
                fence,
                store: high_water.store().get(),
                categories: high_water
                    .categories()
                    .iter()
                    .map(|(id, at)| CategoryPosition {
                        category_id: id.get(),
                        position: at.get(),
                    })
                    .collect(),
                lsn: high_water.lsn().map(lsn::Lsn::get),
            }
        }

        /// The high-water mark the message carries. Categories are sorted, and a category listed twice keeps
        /// its highest position. `None` if a position is above [`position::Position::MAX`], which no
        /// sequencer sends.
        pub fn high_water(&self) -> Option<high_water::HighWater> {
            let categories = self
                .categories
                .iter()
                .map(|entry| {
                    let at = position::Position::new(entry.position)?;

                    Some((category::CategoryId::new(entry.category_id), at))
                })
                .collect::<Option<_>>()?;

            Some(high_water::HighWater::new(
                position::Position::new(self.store)?,
                categories,
                self.lsn.map(lsn::Lsn::new),
            ))
        }
    }
}

#[cfg(doctest)]
#[doc = include_str!("../README.md")]
struct ReadmeDoctests;

#[cfg(test)]
mod tests {
    use pges_core::{category, high_water, lsn, position};

    use super::v1;

    fn at(n: u64) -> position::Position {
        position::Position::new(n).unwrap()
    }

    #[test]
    fn high_water_marks_round_trip() {
        let high = high_water::HighWater::new(
            at(42),
            vec![
                (category::CategoryId::new(3), at(40)),
                (category::CategoryId::new(5), at(42)),
            ],
            Some(lsn::Lsn::new(0x16_B374_D848)),
        );

        let message = v1::WatchResponse::new(7, &high);

        assert_eq!(message.fence, 7);
        assert_eq!(message.lsn, Some(0x16_B374_D848));
        assert_eq!(message.high_water(), Some(high));
        assert_eq!(
            v1::WatchResponse::new(1, &high_water::HighWater::default()).high_water(),
            Some(high_water::HighWater::default())
        );
    }

    #[test]
    fn unsorted_categories_are_sorted() {
        let message = v1::WatchResponse {
            fence: 1,
            store: 9,
            categories: vec![
                v1::CategoryPosition {
                    category_id: 2,
                    position: 9,
                },
                v1::CategoryPosition {
                    category_id: 1,
                    position: 4,
                },
            ],
            lsn: None,
        };

        let high = message.high_water().unwrap();

        assert_eq!(
            high.categories(),
            [
                (category::CategoryId::new(1), at(4)),
                (category::CategoryId::new(2), at(9)),
            ]
        );
    }

    #[test]
    fn positions_above_the_maximum_are_refused() {
        let store = v1::WatchResponse {
            fence: 1,
            store: u64::MAX,
            categories: Vec::new(),
            lsn: None,
        };
        let category = v1::WatchResponse {
            store: 1,
            categories: vec![v1::CategoryPosition {
                category_id: 1,
                position: position::Position::MAX.get() + 1,
            }],
            ..store.clone()
        };

        assert_eq!(store.high_water(), None);
        assert_eq!(category.high_water(), None);
    }
}
